import { build } from "esbuild";
import { readFile } from "node:fs/promises";
import assert from "node:assert/strict";
import { fileURLToPath } from "node:url";
const root=new URL("../",import.meta.url);
await build({entryPoints:[fileURLToPath(new URL("src/lib/site-plan.ts",root)),fileURLToPath(new URL("src/lib/announcements.ts",root))],outdir:"/tmp/chess-plan-check",bundle:true,platform:"node",format:"esm",outExtension:{".js":".mjs"},loader:{".txt":"text"}});
const {migrateSitePlan,cleanCopy}=await import("/tmp/chess-plan-check/site-plan.mjs");
const {announcementStatus,denverInstant}=await import("/tmp/chess-plan-check/announcements.mjs");
const {canonicalPath,renderSitemap,redirectLocation}=await import("../../colorado-heritage/seo-render.mjs");
const original=JSON.parse(await readFile(new URL("src/data/initial-site-content.json",root),"utf8"));
const content=migrateSitePlan(original);
assert.equal(content.faqs.length,10);
assert.equal(content.staff.length,20);
assert.equal(content.staff.filter(p=>p.board).length,7);
assert.ok(content.news.every(p=>p.title?.trim()&&p.path.startsWith("/")),"every imported story must pass admin validation");
assert.ok(!content.news.some(p=>/\/comments-\d+$/.test(p.path)),"unidentified posts need editable titles and neutral clean URLs");
assert.ok(content.pages.find(p=>p.path==="/admissions/apply").markdown.includes("/documents/new-family-enrollment-in-the-chess-independent-school.pdf"),"known new-family enrollment PDF linked directly from Apply");
assert.equal(migrateSitePlan(content),content);
for(const p of original.staff){
  const current=content.staff.find(s=>s.slug===p.slug);
  for(const key of ["photo","photoPositionX","photoPositionY"])assert.equal(current[key],p[key],`${p.slug} ${key} preserved`);
  const text=value=>cleanCopy(value).replace(/\]\([^)]+\)/g,"]").replace(/\s/g,"");
  assert.equal(text(current.bio),text(p.bio),`${p.slug} biography preserved except requested cleanup and links`);
}
const valid=new Set(["/",...content.pages.map(p=>p.path),...content.staff.map(p=>`/about/our-people/${p.slug}`),...content.news.map(p=>p.path),...content.events.map(p=>p.path),...content.documents.map(p=>p.url)]);
for(const key of Object.keys(content.redirects))assert.ok(valid.has(canonicalPath(key,content).split("#")[0]),key);
assert.equal(canonicalPath("/about/faculty/mrs-teri-ong",content),"/about/our-people/mrs-teri-ong");
assert.equal(canonicalPath("/new-events/2015/1/1/old-event",content),"/parents/calendar");
assert.equal(redirectLocation("/about#history","?source=old"),"/about?source=old#history");
const sitemap=renderSitemap(content);
assert.ok(!sitemap.includes("/families/"));
for(const item of [...content.news,...content.events].filter(p=>p.archived))assert.ok(!sitemap.includes(`<loc>https://heritage-site-builder.replit.app${item.path}</loc>`));
assert.equal(cleanCopy("**Parents lead.** We encourage."),"**Parents lead.** We encourage.");
assert.ok(!cleanCopy("umbrella school; IS; eA; DP; 10/8; For 25 years").match(/\bumbrella\b|\bIS\b|\beA\b|\bDP\b|10\/8|25 years/));
const announcement={enabled:true,startsAt:"2026-10-29T09:00",expiresAt:"2026-10-29T10:00"};
assert.equal(announcementStatus(announcement,new Date("2026-10-29T14:59:00Z")),"Scheduled");
assert.equal(announcementStatus(announcement,new Date("2026-10-29T15:00:00Z")),"Live");
assert.equal(announcementStatus(announcement,new Date("2026-10-29T16:00:00Z")),"Expired");
assert.equal(announcementStatus({...announcement,enabled:false}),"Off");
assert.ok(Number.isNaN(denverInstant("2026-03-08T02:30")),"nonexistent DST time rejected");
assert.equal(denverInstant("2026-11-01T01:30"),Date.parse("2026-11-01T07:30:00Z"),"fall DST uses first occurrence");
assert.equal(announcementStatus({enabled:true,expiresAt:"2026-11-01T01:30"},new Date("2026-11-01T08:10:00Z")),"Expired","expired announcement cannot return after clock rollback");
console.log("PASS: migration, preserved staff edits, all redirect targets, sitemap archives, copy cleanup, Denver scheduling including DST.");
